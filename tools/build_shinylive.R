# Build the static calculator with Shinylive.
#
# The app's R files, the R files of the mhspcarpi package at the commit pinned
# in PACKAGE_REF, and the package's model specification are copied into a
# temporary Shiny app directory (Shiny sources the files in R/ before app.R) and
# exported as a static site. The package is bundled as source because it has no
# WebAssembly build; WebAssembly builds of the other dependencies are bundled
# into the site, so visitors download everything from the site's own host.
#
# Usage, from the repository root, with a checkout of the package at the
# pinned commit:
#   Rscript tools/build_shinylive.R [output_dir] [package_source]
# package_source defaults to ../mhspcarpi.

args <- commandArgs(trailingOnly = TRUE)
output_dir <- if (length(args) >= 1L) args[[1L]] else "_site"
package_dir <- if (length(args) >= 2L) args[[2L]] else file.path("..", "mhspcarpi")

# Cloudflare Pages limits (https://developers.cloudflare.com/pages/platform/limits/).
max_file_bytes <- 25 * 1024^2
max_files <- 20000L

# --- Package source at the pinned commit -------------------------------------

package_ref <- trimws(readLines("PACKAGE_REF", warn = FALSE)[[1L]])
if (!file.exists(file.path(package_dir, "DESCRIPTION"))) {
  cli::cli_abort("No package source at {.path {package_dir}}; give its path as the second argument.")
}
package_head <- tryCatch(
  system2("git", c("-C", shQuote(package_dir), "rev-parse", "HEAD"), stdout = TRUE, stderr = FALSE),
  error = function(error) NA_character_,
  warning = function(warning) NA_character_
)
if (!identical(package_head, package_ref)) {
  cli::cli_abort(c(
    "The package source is not at the commit pinned in {.file PACKAGE_REF}.",
    i = "Pinned: {.val {package_ref}}; found: {.val {package_head}}.",
    i = "Check out the pinned commit, or update {.file PACKAGE_REF} after testing the app with it."
  ))
}
package_version <- read.dcf(file.path(package_dir, "DESCRIPTION"), fields = "Version")[[1L]]

# --- App directory ------------------------------------------------------------

app_dir <- file.path(tempdir(), "mhspcarpi-app")
unlink(app_dir, recursive = TRUE)
dir.create(file.path(app_dir, "R"), recursive = TRUE)
app_files <- list.files(file.path("app", "R"), pattern = "[.]R$", full.names = TRUE)
stopifnot(all(file.copy(app_files, file.path(app_dir, "R"))))
package_files <- list.files(file.path(package_dir, "R"), pattern = "[.]R$", full.names = TRUE)
stopifnot(all(file.copy(package_files, file.path(app_dir, "R", paste0("mhspcarpi-", basename(package_files))))))
stopifnot(file.copy(file.path(package_dir, "inst", "extdata", "model_spec.json"), app_dir))
writeLines(
  c(
    "# Generated by tools/build_shinylive.R. Shiny sources the files in R/ first,",
    paste0("# including the mhspcarpi package ", package_version, " at commit ", package_ref, "."),
    "library(shiny)",
    "mhspc_app(model = mhspc_model(\"model_spec.json\"))"
  ),
  file.path(app_dir, "app.R")
)

unlink(output_dir, recursive = TRUE)
shinylive::export(
  app_dir,
  output_dir,
  wasm_packages = TRUE,
  template_params = list(title = "ARPI treatment effect calculator for mHSPC")
)

# Until R has started in the browser, which can take a minute or more on a
# phone's first visit, Shinylive shows only faint gray dots on a white page.
# tools/loading/ replaces them with a loading screen behind the transparent app
# frame, which the app's own page covers once it renders. The screen downloads
# the files R needs at startup with a progress bar, then starts Shinylive, which
# reads them from the browser cache. The list was taken from the requests of a
# first visit with Shinylive assets 0.10.12; a file missing from it only makes
# the bar less accurate.
startup_files <- file.path("shinylive", "webr", c(
  "R.js", "R.wasm", "libRblas.so", "libRlapack.so", "library.js.metadata", "library.data.gz",
  "packages/metadata.rds",
  "vfs/usr/lib/R/library/parallel.js.metadata", "vfs/usr/lib/R/library/parallel.data.gz",
  "vfs/usr/lib/R/library/tcltk.js.metadata", "vfs/usr/lib/R/library/tcltk.data.gz",
  "vfs/usr/lib/R/library/translations.js.metadata", "vfs/usr/lib/R/library/translations.data.gz",
  "vfs/usr/lib/R/library/grDevices/libs.js.metadata", "vfs/usr/lib/R/library/grDevices/libs.data.gz"
))
startup_files <- c(
  startup_files,
  # Packages are versioned, so they are found by name.
  purrr::map_chr(c("purrr", "vctrs"), function(package) {
    found <- list.files(file.path(output_dir, "shinylive", "webr", "packages", package), pattern = "[.]tgz$")
    if (length(found) != 1L) {
      cli::cli_abort("Expected one WebAssembly build of {.pkg {package}} in the exported site.")
    }
    file.path("shinylive", "webr", "packages", package, found)
  })
)
missing_files <- startup_files[!file.exists(file.path(output_dir, startup_files))]
if (length(missing_files) > 0L) {
  cli::cli_abort(c("Startup files are missing from the exported site.", x = "{.file {missing_files}}"))
}
startup_json <- jsonlite::toJSON(
  unname(purrr::map2(startup_files, file.size(file.path(output_dir, startup_files)), list)),
  auto_unbox = TRUE
)

loading_dir <- file.path("tools", "loading")
read_text <- function(name) readLines(file.path(loading_dir, name), warn = FALSE)
prefetch_js <- sub("__STARTUP_FILES__", startup_json, read_text("prefetch.js"), fixed = TRUE)

index_path <- file.path(output_dir, "index.html")
index_html <- readLines(index_path, warn = FALSE)
head_end <- grep("</head>", index_html, fixed = TRUE)
root_line <- grep("id=\"root\"", index_html, fixed = TRUE)
import_line <- grep("import { runExportedApp } from \"./shinylive/shinylive.js\";", index_html, fixed = TRUE)
if (length(head_end) != 1L || length(root_line) != 1L || length(import_line) != 1L) {
  cli::cli_abort("The exported {.file {index_path}} does not have the expected Shinylive structure.")
}
# Shinylive starts only after the downloads; module scripts run after the page
# is parsed, so the prefetch script in the body has started by then.
index_html[[import_line]] <- paste(
  "      await window.mhspcPrefetch;",
  "const { runExportedApp } = await import(\"./shinylive/shinylive.js\");"
)
index_html <- c(
  index_html[seq_len(head_end - 1L)], "<style>", read_text("loading.css"), "</style>",
  index_html[head_end:(root_line - 1L)], read_text("loading.html"), "<script>", prefetch_js, "</script>",
  index_html[root_line:length(index_html)]
)
writeLines(index_html, index_path)

# Long-lived caching for the runtime and packages; the page and app bundle are
# always revalidated so a new release is picked up immediately.
writeLines(
  c(
    "/shinylive/*",
    "  Cache-Control: public, max-age=86400",
    "/app.json",
    "  Cache-Control: no-cache",
    "/",
    "  Cache-Control: no-cache",
    "/index.html",
    "  Cache-Control: no-cache"
  ),
  file.path(output_dir, "_headers")
)

files <- list.files(output_dir, recursive = TRUE, full.names = TRUE, all.files = TRUE)
sizes <- file.size(files)
too_large <- files[sizes > max_file_bytes]
if (length(too_large) > 0L) {
  cli::cli_abort(c(
    "Some files exceed the 25 MiB Cloudflare Pages limit.",
    x = "{.file {too_large}}"
  ))
}
if (length(files) > max_files) {
  cli::cli_abort("The site has {length(files)} files; the limit is {max_files}.")
}
cli::cli_inform(c(
  i = "mhspcarpi {package_version} at commit {.val {package_ref}}.",
  v = "Exported {.file {output_dir}}: {length(files)} files, {format(structure(sum(sizes), class = 'object_size'), units = 'MB')}.",
  i = "Largest file: {.file {basename(files[which.max(sizes)])}} ({format(structure(max(sizes), class = 'object_size'), units = 'MB')})."
))
